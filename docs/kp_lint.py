"""Проверка КП на запрещённые и плавающие формулировки. Запуск: python3 docs/kp_lint.py"""
import re, sys
t=open('docs/KP_beautyscale.md',encoding='utf-8').read()
bad={
 '—':'длинное тире','договор':'слово «договор»','Менеджер':'строка «Менеджер / Телефон»','Телефон:':'строка «Менеджер / Телефон»',
 '✓':'галочка вместо конкретики','частично':'плавающее «частично»','полностью':'плавающее «полностью»',
 'по необходимости':'плавающее «по необходимости»','ежемесячный контроль':'плавающее «ежемесячный контроль»',
 'при необходимости':'плавающее «при необходимости»','примерно':'плавающее «примерно»','и т.д.':'«и т.д.»','и др.':'«и др.»',
 'и так далее':'«и так далее»','по возможности':'плавающее «по возможности»','регулярно':'плавающее «регулярно»',
 'быстро':'плавающее «быстро»','оперативно':'плавающее «оперативно»','1 000+':'«+» вместо числа','соцсети ':'«соцсети» без перечня (проверить контекст)',
}
fails=0
for i,l in enumerate(t.splitlines(),1):
    for k,v in bad.items():
        if k in l:
            if k=='соцсети ' and re.search(r'Instagram',l): continue
            print(f'{i}: {v}: ...{l[max(0,l.find(k)-30):l.find(k)+40]}'); fails+=1
    if re.search(r'\d\s?%',l) and 'StatCounter' not in l: print(f'{i}: процент вне статистики: {l[:80]}'); fails+=1
print('OK' if not fails else f'Замечаний: {fails}')
sys.exit(1 if fails else 0)
